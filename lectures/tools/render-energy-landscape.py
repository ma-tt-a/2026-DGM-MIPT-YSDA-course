"""Original one-dimensional energy landscape for Lecture 6."""
from pathlib import Path
import hashlib
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

root = Path(__file__).resolve().parents[1]
figs = root / "lecture6/public/figs"
plt.rcParams.update({"font.family": "Arial", "font.size": 16,
                     "text.color": "#17324d", "axes.labelcolor": "#17324d",
                     "xtick.color": "#587083", "ytick.color": "#587083",
                     "svg.hashsalt": "dgm-energy-landscape"})

def energy(x):
    # Negative log of a 1D Gaussian mixture, up to a constant.
    # Its density is also the first-coordinate marginal of the Langevin demo.
    return -np.logaddexp(-0.5 * ((x + 1.5) / 0.7) ** 2,
                        -0.5 * ((x - 1.5) / 0.7) ** 2)

x = np.linspace(-3.5, 3.5, 1001)
offset = energy(x).min()
fig, ax = plt.subplots(figsize=(6.2, 3.4))
ax.plot(x, energy(x) - offset, color="#007f82", lw=3)
ax.fill_between(x, energy(x) - offset, color="#007f82", alpha=0.06)
for a, b in [(-3.1, -2.5), (3.1, 2.5)]:
    ax.annotate("", xy=(b, energy(b) - offset),
                xytext=(a, energy(a) - offset),
                arrowprops={"arrowstyle": "->", "color": "#8854c0", "lw": 2.5})
ax.set(xlim=(-3.6, 3.6), ylim=(-0.25, 4.5), xticks=[-3, 0, 3], yticks=[0, 2, 4])
ax.set_xlabel(r"Data point $x$")
ax.set_title(r"Energy $E(x)$", loc="left", fontsize=18, pad=12)
ax.spines[["top", "right"]].set_visible(False)
for edge in ["left", "bottom"]:
    ax.spines[edge].set_color("#bbced8")
fig.tight_layout(pad=0.7)
target = figs / "energy-landscape.svg"
fig.savefig(target, metadata={"Date": None}, transparent=True)
plt.close(fig)
target.write_text("\n".join(line.rstrip() for line in target.read_text().splitlines()) + "\n")

manifest = figs / "sources.json"
sources = json.loads(manifest.read_text())
sources[target.name] = {
    "source": "https://yann.lecun.org/exdb/publis/pdf/lecun-06.pdf",
    "description": "Original analytic plot, not copied from the cited tutorial. One-dimensional energy E(x)=-log p(x)+const, shifted to have minimum zero, for an equally weighted Gaussian mixture with means +/-1.5 and sigma=0.7. This density is also the first-coordinate marginal of the Langevin demo. Arrows point downhill. Generated by tools/render-energy-landscape.py; citation supplies EBM background.",
    "sha256": hashlib.sha256(target.read_bytes()).hexdigest()
}
manifest.write_text(json.dumps(sources, indent=2) + "\n")
